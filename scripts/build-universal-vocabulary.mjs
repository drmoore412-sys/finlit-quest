#!/usr/bin/env node
// Universal approved-financial-term vocabulary (owner assignment 2026-11-18, narrowed to financial terms only).
//   node scripts/build-universal-vocabulary.mjs generate   write content/universal-vocabulary-v1.json/.js
//   node scripts/build-universal-vocabulary.mjs check      verify the committed files equal a fresh build
// The vocabulary is exactly the approved curriculum terms (src/answer-expansion.js loadDictionary, 211 terms) that fit a wheel (3-9 letters).
// It contains NO general English words, abbreviations, reserve terms or supplements: any approved term from any world is accepted by any wheel that
// can spell it, and nothing else is added. Required answers (the exhaustive-answer rule) are unchanged; this only lets an approved term count where a
// puzzle's own answer list would not (for example generated Credit/Crypto bank puzzles).
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const MIN = 3, MAX = 9;
const OUT_JSON = path.join(ROOT, "content/universal-vocabulary-v1.json"), OUT_JS = path.join(ROOT, "content/universal-vocabulary-v1.js");
function build() {
  const A = require("../src/answer-expansion.js");
  const dictionary = A.loadDictionary(ROOT);
  const all = [...dictionary.keys()].sort();
  const financial = all.filter(w => /^[A-Z]+$/.test(w) && w.length >= MIN && w.length <= MAX);
  return {
    schema: 2, vocabularyVersion: "2.0.0", minLength: MIN, maxLength: MAX,
    note: "Approved financial curriculum terms accepted by every wheel that can spell them, in every world. Gameplay data only: no new terms, definitions or key terms. General English words are intentionally not part of this vocabulary.",
    sources: { approvedTerms: "src/answer-expansion.js loadDictionary" },
    counts: { approvedTerms: all.length, total: financial.length, financial: financial.length, general: 0, tooLongForAnyWheel: all.length - financial.length },
    tooLongForAnyWheel: all.filter(w => !financial.includes(w)),
    financial, general: [],
  };
}
const doc = build();
const runtime = { schema: doc.schema, vocabularyVersion: doc.vocabularyVersion, minLength: MIN, maxLength: MAX, counts: doc.counts, financial: doc.financial.join(" "), general: "" };
const jsText = `// GENERATED by scripts/build-universal-vocabulary.mjs - do not edit by hand.\nwindow.FINLIT_UNIVERSAL_VOCABULARY=Object.freeze(${JSON.stringify(runtime)});\n`;
if ((process.argv[2] || "check") === "generate") {
  fs.writeFileSync(OUT_JSON, JSON.stringify(doc, null, 1) + "\n"); fs.writeFileSync(OUT_JS, jsText);
  console.log(JSON.stringify(doc.counts));
} else {
  const ok = fs.readFileSync(OUT_JSON, "utf8") === JSON.stringify(doc, null, 1) + "\n" && fs.readFileSync(OUT_JS, "utf8") === jsText;
  if (!ok) { console.error("universal vocabulary is out of date; run generate"); process.exit(1) }
  console.log("ok", JSON.stringify(doc.counts));
}
