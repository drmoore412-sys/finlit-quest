#!/usr/bin/env node
// Currency bonus assignment (owner assignment 2026-11-18).
//   node scripts/build-currency-bonus.mjs generate   write content/currency-bonus-v1.json/.js for the 61 released levels
//   node scripts/build-currency-bonus.mjs check      verify the committed assignment equals a fresh deterministic computation
// One designated ISO 4217 code per puzzle at most, chosen from the 20 approved codes the wheel can spell (repeated letters respected, never a required answer),
// except the ten owner-designated puzzles, which use their designated code from the nine further approved codes (src/currency-bonus.js DESIGNATED).
// Wheels, key terms and required answers are inputs only and are never changed. Puzzles with no spellable code are recorded as null.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const mode = process.argv[2] || "check";
const Currency = require("../src/currency-bonus.js");
const Bank = require("../src/puzzle-bank-engine.js");
const H = require("../tests/unified-release-helpers.js");
const levels = require("../content/unified-levels-v2.js");

function releasedPuzzles() {
  const library = new Map([...H.canonicalMap(), ...levels.puzzles.map(p => [p.id, p])]);
  return levels.manifest.entries.map(entry => {
    const puzzle = library.get(entry.puzzleId);
    if (!puzzle) throw new Error("missing puzzle " + entry.puzzleId);
    const model = Bank.puzzleModel(puzzle);
    return { id: puzzle.id, world: puzzle.worldId, anchor: puzzle.anchorWord, letters: model.letters, requiredWords: model.words };
  });
}
function compute() {
  const puzzles = releasedPuzzles();
  const assignments = Currency.assign(puzzles);
  const usage = {};
  Object.values(assignments).forEach(code => { if (code) usage[code] = (usage[code] || 0) + 1 });
  return {
    schema: 1, version: "1.0.0",
    note: "Designated three-letter currency bonus per released puzzle (null = no approved code can be spelled from that wheel). Generated deterministically by scripts/build-currency-bonus.mjs; do not edit by hand.",
    pool: Currency.POOL.map(c => ({ code: c.code, name: c.name })),
    designatedPool: Currency.DESIGNATED_POOL.map(c => ({ code: c.code, name: c.name })),
    designated: Currency.DESIGNATED,
    puzzleCount: puzzles.length,
    assignments,
    usage: Object.fromEntries(Object.entries(usage).sort()),
    withoutCode: puzzles.filter(p => !assignments[p.id]).map(p => p.id),
  };
}
const OUT_JSON = path.join(ROOT, "content/currency-bonus-v1.json"), OUT_JS = path.join(ROOT, "content/currency-bonus-v1.js");
const doc = compute();
if (mode === "generate") {
  fs.writeFileSync(OUT_JSON, JSON.stringify(doc, null, 1) + "\n");
  fs.writeFileSync(OUT_JS, `// GENERATED by scripts/build-currency-bonus.mjs - do not edit by hand.\nwindow.FINLIT_CURRENCY_BONUS=Object.freeze(${JSON.stringify({ schema: doc.schema, version: doc.version, assignments: doc.assignments })});\n`);
  console.log("assigned", Object.values(doc.assignments).filter(Boolean).length, "of", doc.puzzleCount, JSON.stringify(doc.usage), "none:", doc.withoutCode.length);
} else {
  const onDisk = JSON.parse(fs.readFileSync(OUT_JSON, "utf8"));
  if (JSON.stringify(onDisk) !== JSON.stringify(doc)) { console.error("currency-bonus-v1.json is out of date; run generate"); process.exit(1) }
  const js = fs.readFileSync(OUT_JS, "utf8");
  if (!js.includes(JSON.stringify(doc.assignments))) { console.error("currency-bonus-v1.js out of sync"); process.exit(1) }
  console.log("ok");
}
