// Generates content/unified-levels-v2.js (production data for main-levels sequenceVersion 2) from the owner-approved sources:
//   content/unified-sequence-v2-gated-dev.json, unified-prototype-12-puzzles-dev.json, unified-prototype-12-whitelist-dev.json,
//   unified-legacy-v1-baseline.json. Only the release flags change (devOnly, environment, releaseGate, nine entries approved).
// Usage: node scripts/build-unified-levels-v2.mjs [--check]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = f => JSON.parse(fs.readFileSync(path.join(root, f), "utf8"));
export function build() {
  const gated = read("content/unified-sequence-v2-gated-dev.json"), puzzleFile = read("content/unified-prototype-12-puzzles-dev.json"), wl = read("content/unified-prototype-12-whitelist-dev.json"), baseline = read("content/unified-legacy-v1-baseline.json");
  const ids = new Set(puzzleFile.puzzles.map(p => p.id));
  const manifest = {
    ...gated, devOnly: false, environment: "production",
    note: "main-levels sequenceVersion 2 (61 levels): the 52 unchanged canonical v1 puzzles under the owner-approved legacy compatibility exception, six in-place upgrades (positions 6, 9, 11, 15, 18, 28) and three appended levels. Owner-authorized for production 2026-11-14.",
    releaseGate: { status: "open", authorizedBy: "owner", authorizedOn: "2026-11-14", resolved: [...gated.releaseGate.resolved, "ownerActivationApproval", "releaseClassificationOfLegacyV1Entries"] },
    entries: gated.entries.map(e => ids.has(e.puzzleId) ? { ...e, releaseStatus: "approved" } : e),
  };
  const whitelist = { ...wl, devOnly: false, entries: wl.entries.filter(e => (e.approvedInPuzzles || []).some(id => ids.has(id))) };
  const data = { schema: 1, manifest, puzzles: puzzleFile.puzzles, whitelist, baseline };
  return `// GENERATED by scripts/build-unified-levels-v2.mjs — do not edit by hand. Production data for main-levels sequenceVersion 2.\n(function(root,data){if(typeof module==="object"&&module.exports)module.exports=data;root.FinLitUnifiedLevelsV2=data})(typeof globalThis!=="undefined"?globalThis:this,${JSON.stringify(data)});\n`;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = path.join(root, "content/unified-levels-v2.js"), text = build();
  if (process.argv.includes("--check")) { if (fs.readFileSync(out, "utf8") !== text) { console.error("content/unified-levels-v2.js is stale"); process.exit(1); } console.log("up to date"); }
  else { fs.writeFileSync(out, text); console.log("wrote", out, text.length, "bytes"); }
}
